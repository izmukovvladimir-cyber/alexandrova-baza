  function onesText(a, b, a8, b8) {
    var x = band(a), y = band(b);
    if (x === "0" && y === "0") return ONES_SYM["0|0"];
    if (x === "0") return zeroText(ME, PT, b);
    if (y === "0") return zeroText(PT, ME, a);
    if (x === y) return ONES_SYM[x + "|" + x];
    var meStrong = ORDER[x] > ORDER[y];
    var wn = meStrong ? b8 : a8, w8 = wn >= 1 && wn <= 2;
    var k = meStrong ? y + "|" + x : x + "|" + y;
    return onesAsym(k, meStrong ? ME : PT, meStrong ? PT : ME, w8);
  }

