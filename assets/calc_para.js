  /* ---------- Восьмёрки ---------- */
  function eightOne(n, P) {
    if (n === 2) return [P.Gen + " две восьмёрки", "В лучшем проявлении это терпение без потери лица, в худшем человек уходит в роль жертвы."];
    if (n >= 3) return [P.Gen + " три восьмёрки и больше", "В худшем проявлении это придирки к каждой мелочи, правда в глаза без жалости и лёгкий шантаж. Такое поведение портит отношения, даже когда по другим цифрам пара сходится."];
    return null;
  }

  function eightText(a, b) {
    var ca = a >= 1 && a <= 2, cb = b >= 1 && b <= 2;
    var out = [];
    if (ca && cb) {
      out.push(["Кто гасит ссоры", "Вы оба: у каждого есть восьмёрки. Они дают терпение и сдерживают обоих, поэтому резких конфликтов у вас, скорее всего, будет меньше."]);
    } else if (ca || cb) {
      var P = ca ? ME : PT, n = ca ? a : b;
      out.push(["Кто гасит ссоры", P.Nom + ": " + P.gen + " " + (n === 1 ? "одна восьмёрка" : "две восьмёрки") + ". Такой человек терпеливее и умеет устранять конфликт. По словам школы, в его руках ключик от отношений: он не цепляется к брошенным носкам и плохо вымытой посуде. Скорее улыбнётся и скажет доброе слово."]);
    } else if (a === 0 && b === 0) {
      out.push(["Кто гасит ссоры", "Восьмёрок нет ни у вас, ни у партнёра. Восьмёрка отвечает за терпение и чувство долга, поэтому терпение в ссоре вам обоим придётся растить сознательно."]);
    } else {
      out.push(["Кто гасит ссоры", "Спокойного терпения, которое дают одна-две восьмёрки, нет ни у кого из вас."]);
    }
    [eightOne(a, ME), eightOne(b, PT)].forEach(function (p) { if (p) out.push(p); });
    return out;
  }

  /* Строка о восьмёрках в карточке характера, согласованная с карточкой терпения. */
  function eightNote(a, b, x, y) {
    if ((x === "w" && y === "s") || (x === "s" && y === "w")) {
      var meLead = x === "s", L = meLead ? ME : PT;
      var lead = meLead ? a : b, other = meLead ? b : a;
      if (lead === 0) return ["Как ведёт ведущий", L.Gen + " восьмёрок нет, поэтому " + (meLead ? "ведёте вы жёстко. Если второй спорит ради спора, вы можете" : "партнёр ведёт жёстко. Если второй спорит ради спора, партнёр может") + " резко поставить его на место."];
      if (lead <= 2) return ["Как ведёт ведущий", L.Gen + " есть восьмёрки. Слабее они " + (meLead ? "вас" : "партнёра") + " не делают, но " + (meLead ? "давить вы не будете и не станете указывать второму на недостатки: поддержите и поправите мягко." : "давить партнёр не будет и не станет указывать второму на недостатки: поддержит и поправит мягко.") +
        (other >= 1 && other <= 2 ? " Восьмёрки есть и у второго. Похожую пару, где восьмёрки сдерживают обоих, школа называет практически идеальной." : "")];
      return ["Как ведёт ведущий", L.Gen + " три восьмёрки и больше. В худшем проявлении это придирки к мелочам: про это в карточке ниже."];
    }
    if (x === "s" && y === "s") {
      var ca = a >= 1 && a <= 2, cb = b >= 1 && b <= 2;
      if (ca || cb) return ["Шанс ужиться", (ca && cb ? "У вас обоих есть" : ca ? "У вас есть" : "У партнёра есть") + " одна-две восьмёрки. Они дают готовность уступить и пойти на компромисс, а для двух сильных характеров это и есть условие, чтобы ужиться."];
    }
    return null;
  }

  function fill(id, paras) {
    var box = document.getElementById(id);
    box.innerHTML = "";
    paras.forEach(function (p) {
      var x = PM.el("p", "para-p");
      x.appendChild(PM.el("strong", null, p[0] + ". "));
      x.appendChild(document.createTextNode(p[1]));
      box.appendChild(x);
    });
  }

  function rep(k, n) { return n ? new Array(n + 1).join(String(k)) : "нет"; }

  var form = document.getElementById("para-form");
  var checkA = PM.dateField(document.getElementById("date-a"));
  var checkB = PM.dateField(document.getElementById("date-b"));
  var res = document.getElementById("para-result");

  form.addEventListener("submit", function (ev) {
    ev.preventDefault();
    var pa = checkA(), pb = checkB();
    if (!pa || !pb) { res.hidden = true; return; }
    var a = PM.matrix(pa.d, pa.m, pa.y).cells, b = PM.matrix(pb.d, pb.m, pb.y).cells;
    document.getElementById("para-tab").innerHTML =
      "<tr><th></th><th>Вы</th><th>Партнёр</th></tr>" +
      [[1, "Характер"], [6, "Труд, быт"], [8, "Терпение"]].map(function (r) {
        return "<tr><td>" + r[1] + "</td><td>" + rep(r[0], a[r[0]]) + "</td><td>" + rep(r[0], b[r[0]]) + "</td></tr>";
      }).join("");
    var ones = onesText(a[1], b[1], a[8], b[8]).slice();
    var note = eightNote(a[8], b[8], band(a[1]), band(b[1]));
    if (note) ones.push(note);
    fill("para-1", ones);
    fill("para-6", sixText(a[6], b[6]));
    fill("para-8", eightText(a[8], b[8]));
    document.getElementById("para-8-card").hidden = false;
    res.hidden = false;
    res.scrollIntoView({ behavior: "smooth", block: "start" });
  });
