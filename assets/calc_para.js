/* Калькулятор «Кто в паре главный»: две даты → единицы и шестёрки.
   Тексты по урокам курса «Профессионал» st1_15 (совместимость), сверка: work/tg_leadmagnets_2511/calc_research.md */
(function () {
  "use strict";
  var PM = window.PM;

  function oneBand(n) { return n === 0 ? "0" : n <= 2 ? "w" : n === 3 ? "m" : n <= 5 ? "s" : "x"; }
  var ONES = {
    "w|w": "У вас обоих мягкий характер. Каждому хочется показать свою независимость, а брать на себя трудные решения не хочется никому, поэтому ответственность легко переходит туда-обратно. Помогает сразу разделить зоны: это решаю я, это решаешь ты. Недовольство лучше говорить пожеланием, без упрёков.",
    "w|m": "У одного из вас характер в золотой середине, у другого мягче. Партнёр с тремя единицами уживается почти с любым: он поддержит и подбодрит второго. Ведущий в паре у вас есть.",
    "w|s": "В паре понятно, кто ведёт: партнёр с сильным характером берёт решения и ответственность на себя.",
    "w|x": "Это одно из самых удачных сочетаний. Партнёр с очень сильным характером спокойно отдаёт второму право командовать в обычной жизни, а в трудный момент сам берёт всё на себя. Вопрос, кто главный, у вас почти не встаёт.",
    "m|m": "Два характера в золотой середине уживаются легко, спорить за лидерство вам незачем. Слабое место одно: без общего дела интерес друг к другу может угаснуть до равнодушия. Поэтому вам особенно важно что-то общее.",
    "m|s": "Ведёт в паре тот, у кого характер сильнее. Партнёр с тремя единицами на рожон не лезет и уступает там, где вопрос не принципиальный, поэтому уживаетесь вы хорошо.",
    "m|x": "Хорошее сочетание. Партнёр с очень сильным характером спокойно делится главенством, а в сложной ситуации берёт её на себя. Партнёр с тремя единицами уживается с ним без борьбы.",
    "s|s": "Два лидера. Ссориться вы, скорее всего, будете редко, зато каждый легко уходит в свою сторону и может видеть в партнёре соперника. Держат такую пару общие цели и ясный договор, кто за что отвечает. Сильнее всего вас сближает трудность, которую проходите вместе.",
    "s|x": "Сочетание непредсказуемое. Решительность партнёра с четырьмя-пятью единицами задевает того, у кого характер ещё сильнее, и он может вспыхнуть. Партнёру с четырьмя-пятью единицами лучше самому брать ответственность и не задевать второго за живое.",
    "x|x": "Самое трудное сочетание по характеру. Каждый из вас привык быть главным, и уступать друг другу будет очень тяжело.",
    "0|any": "У одного из вас в матрице нет единиц. Такой человек легко подстраивается и спорить за главенство не будет. Ему трудно заставить себя действовать, когда ситуация требует. Рядом с ним важно подбадривать и замечать каждое его решение, без давления.",
    "0|0": "В обеих матрицах нет единиц. Такое сочетание школа разбирает только лично, по обеим матрицам целиком."
  };
  var ORDER = { "0": 0, w: 1, m: 2, s: 3, x: 4 };

  function onesText(a, b, ca, cb) {
    var x = oneBand(a), y = oneBand(b);
    if (x === "0" && y === "0") return ONES["0|0"];
    if (x === "0" || y === "0") {
      return (x === "0" ? "У вас" : "У партнёра") + " в матрице нет единиц. " + ONES["0|any"].split(". ").slice(1).join(". ");
    }
    var k = ORDER[x] <= ORDER[y] ? x + "|" + y : y + "|" + x;
    if (k === "w|s") {
      var meStrong = x === "s";
      var has8 = (meStrong ? ca : cb)[8] > 0;
      return "В паре понятно, кто ведёт: " + (meStrong
        ? "вы. У вас сильный характер, решения и ответственность вы берёте на себя."
        : "партнёр. У него сильный характер, решения и ответственность он берёт на себя.") +
        (has8 ? " Восьмёрки делают ведущего мягче: он ведёт с терпением и поддерживает второго."
              : " Восьмёрок у ведущего нет, поэтому, если второй спорит ради спора, он может резко поставить его на место.");
    }
    return ONES[k];
  }

  function sixText(a, b) {
    var x = a >= 2, y = b >= 2;
    if (x && y) return "Вы оба работящие и рукастые, домашние дела никого из вас не тяготят. Спорить, кому сегодня мыть посуду, вам почти не придётся.";
    if (x || y) return (x ? "Вам" : "Партнёру") + " домашние дела даются легче: у " + (x ? "вас" : "него") + " две шестёрки и больше, и рутина не тяготит. " + (x ? "Партнёру" : "Вам") + " быт даётся тяжелее. Делите хозяйство по матрице, без оглядки на то, кто мужчина, а кто женщина. Если делить наоборот, быт быстро станет поводом для ссор.";
    return "Ни у кого из вас нет двух шестёрок, поэтому быт не держится сам собой. Договоритесь заранее, кто за что отвечает дома, чтобы он не стал поводом для упрёков.";
  }

  function rep(k, n) { return n ? new Array(n + 1).join(String(k)) : "нет"; }

  var form = document.getElementById("para-form");
  var checkA = PM.dateField(document.getElementById("date-a"));
  var checkB = PM.dateField(document.getElementById("date-b"));
  var res = document.getElementById("para-result");

  form.addEventListener("submit", function (ev) {
    ev.preventDefault();
    var pa = checkA(), pb = checkB();
    if (!pa || !pb) { res.hidden = true; return; }
    var a = PM.matrix(pa.d, pa.m, pa.y).cells, b = PM.matrix(pb.d, pb.m, pb.y).cells;
    document.getElementById("para-tab").innerHTML =
      "<tr><th></th><th>Вы</th><th>Партнёр</th></tr>" +
      [[1, "Характер"], [6, "Труд, быт"]].map(function (r) {
        return "<tr><td>" + r[1] + "</td><td>" + rep(r[0], a[r[0]]) + "</td><td>" + rep(r[0], b[r[0]]) + "</td></tr>";
      }).join("");
    document.getElementById("para-1").textContent = onesText(a[1], b[1], a, b);
    document.getElementById("para-6").textContent = sixText(a[6], b[6]);
    res.hidden = false;
    res.scrollIntoView({ behavior: "smooth", block: "start" });
  });
})();
