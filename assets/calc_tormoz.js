  function run(p, si, fast) {
    busy = true;
    box.hidden = false;
    content.hidden = true;
    loading.hidden = false;
    var wait = fast ? Promise.resolve() : new Promise(function (res) { setTimeout(res, 2000); });
    if (!fast) box.scrollIntoView({ behavior: "smooth", block: "start" });
    return wait.then(function () { return render(p, si); }).then(function (r) {
      loading.hidden = true;
      content.hidden = false;
      busy = false;
      if (!fast) box.scrollIntoView({ behavior: "smooth", block: "start" });
      return r;
    });
  }

