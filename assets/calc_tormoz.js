  function drawPng(r) {
    return PM.fontsReady().then(function () {
      var cv = document.getElementById("tormoz-canvas");
      var ctx = PM.cardFrame(cv, "Ваш денежный тормоз", SITE, "Посчитайте свой по дате рождения");
      var X = 90, W = 1080, maxW = W - 2 * X;
      /* плитка с цифрой */
      PM.rrect(ctx, X, 200, 250, 250, 44);
      ctx.fillStyle = "rgba(255,255,255,.12)";
      ctx.fill();
      ctx.fillStyle = "#ffffff";
      ctx.font = "700 190px " + PM.SANS;
      ctx.textAlign = "center";
      ctx.fillText(String(r.digit), X + 125, 395);
      ctx.textAlign = "left";
      ctx.fillStyle = "#eadff9";
      ctx.font = "600 44px " + PM.SANS;
      var y = 290;
      PM.wrap(ctx, r.countLine.replace(/\.$/, ""), maxW - 290).forEach(function (ln) { ctx.fillText(ln, X + 290, y); y += 56; });

      function part(label, text, top) {
        ctx.fillStyle = "#d5c1f2";
        ctx.font = "700 30px " + PM.SANS;
        if ("letterSpacing" in ctx) ctx.letterSpacing = "3px";
        ctx.fillText(label.toUpperCase(), X, top);
        if ("letterSpacing" in ctx) ctx.letterSpacing = "0px";
        ctx.fillStyle = "#ffffff";
        ctx.font = "700 68px " + PM.SERIF;
        var yy = top + 78;
        PM.wrap(ctx, text, maxW).forEach(function (ln) { ctx.fillText(ln, X, yy); yy += 70; });
        return yy;
      }
      y = part("Сильная сторона", r.plusShort, 560);
      part("Тормоз", r.minusShort, y + 60);
      return PM.toBlob(cv);
    });
  }

